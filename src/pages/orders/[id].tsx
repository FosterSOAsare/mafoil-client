import Head from "next/head";
import React, { useEffect } from "react";
import Image from "next/image";
import { toast } from "react-toastify";
import { useRouter } from "next/router";

import { useLazyFetchAnOrderRequestQuery, useCancelOrderRequestMutation } from "@/apis/orderApi";
import useCreateErrorFromApiRequest from "@/hooks/useCreateErrorFromApiRequest";

import Header from "@/components/molecules/Header";
import Footer from "@/components/molecules/Footer";
import Loading from "@/components/atom/Loading";
import { Loading1 } from "@/components/atom/Loading";

const OrderPage = () => {
	const { query, isReady } = useRouter();

	const [fetchOrder, { data, error, isLoading }]: any = useLazyFetchAnOrderRequestQuery();
	const [cancelOrder, { data: order, error: cancelError, isLoading: cancelOrderLoading }]: any = useCancelOrderRequestMutation();

	useEffect(() => {
		if (!isReady) return;
		if (isReady && !query?.id) {
			// Display 404
			return;
		}
		fetchOrder(query?.id);
	}, [isReady, query?.id]);

	useEffect(() => {
		if (!order) return;
		toast.success("Order has successfully been cancelled", { autoClose: 1500 });
	}, [order]);
	// Handle error from cancelling and fetching order
	useCreateErrorFromApiRequest(error);
	useCreateErrorFromApiRequest(cancelError);
	return (
		<>
			<Head>
				<title>Mafo.il - View An Order - {query?.id as string}</title>
				<meta name="description" content="Generated by create next app" />
				<meta name="viewport" content="width=device-width, initial-scale=1" />
				<link rel="icon" href="/favicon.ico" />
			</Head>
			<Header />
			<main className="w-full min-h-screen px-4 bg-white relative pb-6">
				<section className="w-full h-[30vh] flex items-center justify-center flex-col " id="hero">
					<h1 className="text-4xl mb-6 font-bold">AN ORDER</h1>

					{data?.status !== "cancelled" && !isLoading && (
						<div className="flex items-center justify-between h-auto w-4/5 md:w-1/3 overflow-hidden rounded-[5px]">
							{[1, 2, 3, 4, 5].map((item, index) => (
								<span
									key={index}
									className={`w-6 h-6 progress ${index < data?.step ? "filled" : "empty"}  rounded-full flex items-center justify-center  font-bold text-sm`}
									style={{ zIndex: 5 - (index + 1) }}>
									{item}
								</span>
							))}
						</div>
					)}
					{data?.status === "cancelled" && !isLoading && <p className="text-red-500 -mt-4 font-bold text-xl text-center">Order Cancelled</p>}
				</section>

				<section id="products" className="max-w-5xl  mx-auto h-auto mt-4 w-full gap-6 justify-between">
					{!isLoading && data?.cart?.length > 0 && (
						<>
							<h3 className="text-3xl font-bold mb-7">ORDERED ITEMS</h3>
							<article className="w-full flex flex-col items-center max-w-5xl mx-auto justify-center">
								<div className="w-full overflow-x-auto">
									<div className="w-[150%] md:w-full font-medium h-auto pb-3 flex items-center justify-between border-b">
										<p className="w-[50%]">PRODUCT</p>
										<p className="w-[25%] text-center">QUANTITY</p>
										<p className="w-[25%] text-center">PRICE</p>
										{/* {data?.status !== "cancelled" && (
										<>
											<p className="w-[15%] text-center">{data?.status == "complete" ? "TOTAL" : data?.status === "pending" ? "EXPECTED" : ""} PROFIT</p>
											<p className="w-[15%] text-center">PROFIT PERCENT</p>
										</>
									)} */}
									</div>
									{data?.cart?.map((product: any, index: number) => {
										const { count, price, totalItemsProfit, profitPercent } = product;
										return (
											<div key={index} className="w-[150%]  md:w-full h-auto py-8 flex items-center justify-between border-b">
												<div className="w-[50%] h-full flex items-center gap-4">
													<div className="w-28 h-20 relative">
														<Image src={product?.image?.url} alt="product Image" fill />
													</div>
													<div className="">
														<h3 className="text-[12px] md:text-sm text-bold text-black mb-2">{product?.name}</h3>
														<p className="text-[12px]">GH₵{(product?.price).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}</p>
													</div>
												</div>
												<p className="w-[25%] flex flex-col items-center justify-center">{count}</p>
												<p className="w-[25%] text-center text-sm font-medium">
													GH₵{(price * count).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
												</p>
												{/* Removed all stuff related to profit */}

												{/* {data.status !== "cancelled" && (
												<>
													<p className={`w-[15%] ${data?.status === "complete" ? "text-green-500" : "text-slate-500"} font-bold text-center`}>
														GH₵{totalItemsProfit.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
													</p>
													<p className={`w-[15%] ${data?.status === "complete" ? "text-green-500" : "text-slate-500"} font-bold text-center`}>{profitPercent}%</p>
												</>
											)} */}
											</div>
										);
									})}
								</div>
								<article className="w-[45%] mr-auto mt-8">
									<h3 className="font-bold">Subtotal: GH₵{data?.totalPrice.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })} </h3>
									{/* {data?.status !== "cancelled" && (
										<>
											<p className={`font-medium text-green-600`}>
												{data.status === "complete" ? "Total" : data?.status === "pending" ? "Expected" : ""} Profit: GH₵
												{data?.totalProfit.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}{" "}
											</p>
											<p className="font-medium opacity-60 text-sm">
												Average Profit Percentage: {data?.avgProfitPercent.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}%
											</p>
										</>
									)} */}

									{/* You can only cancel an order when it is at step 1 */}
									{data?.step === 1 && data?.status === "pending" && (
										<div className="w-full mt-4">
											<button
												disabled={cancelOrderLoading}
												onClick={() => {
													// Implement cancel order
													cancelOrder(query?.id);
												}}
												className={`mt-4 w-[180px]! flex items-center justify-center bg-black text-white relative group h-12 overflow-hidden`}>
												<div
													className={`w-full h-full bg-brown absolute flex items-center justify-center transition-all duration-300 top-0 group-hover:left-0 z-1 ${
														cancelOrderLoading ? "left-0" : "-left-full"
													}`}>
													{cancelOrderLoading && <Loading1 />}
												</div>
												{!cancelOrderLoading && (
													<p className="relative z-2 transition-all duration-75 group-hover:text-white uppercase text-[12px] font-medium">Cancel Order</p>
												)}
											</button>
										</div>
									)}
								</article>
							</article>
						</>
					)}

					{isLoading && (
						<div className="w-full h-[60vh] flex items-center justify-center">
							<Loading />
						</div>
					)}

					{!isLoading && data?.cart?.length === 0 && <p className="text-center">Your cart is currently empty.</p>}
				</section>
			</main>
			<Footer />
		</>
	);
};

export default OrderPage;
